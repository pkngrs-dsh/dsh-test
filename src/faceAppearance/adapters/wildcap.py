"""WildCap's ICT-atlas DPPS refinement with reusable weights and request-local state.

Adapted from 03_WildCap/wildcap/run_wildcap.py (GPL-3.0); see
faceAppearance/vendor/wildCap/SOURCES.md. This is not a multiview BRDF fit:
the photometric likelihood uses diffuse plus fixed geometric normals. Specular
and tangent normals are generated by the joint learned reflectance prior.

Input/output diffuse follows upstream's gamma-2.2 encoded RGB convention, not
an assertion of calibrated physical albedo. Specular is a linear scalar;
tangentNormal contains signed, normalized XYZ vectors, not RGB PNG values.
"""

from __future__ import annotations

import hashlib
import logging
import threading
from pathlib import Path
from time import perf_counter
from typing import Any

import numpy as np
from PIL import Image

from ..texture import validateTriangles

logger = logging.getLogger(__name__)


def cropForResolution(resolution: int) -> tuple[int, int, int, int]:
    """Return x1, x2, y1, y2 in the ORIGINAL fixed ICT training atlas."""
    if resolution not in (512, 1024):
        raise ValueError("workingResolution must be 512 or 1024")
    return tuple(value * resolution // 1024 for value in (128, 896, 64, 832))


def validateMask(mask: np.ndarray, shape: tuple[int, int], name: str) -> np.ndarray:
    mask = np.asarray(mask)
    if mask.shape != shape or not np.isfinite(mask).all():
        raise ValueError(f"{name} must be finite with shape {shape}")
    if not np.logical_or(mask == 0, mask == 1).all():
        raise ValueError(f"{name} must be binary 0/1 or bool; threshold soft masks explicitly")
    return mask.astype(bool, copy=True)


def validateLightingSchedule(schedule: str, effectiveLocalMask=None) -> str:
    """Validate the opt-in global-only control without touching device state."""
    if schedule not in ("upstream", "global301"):
        raise ValueError("lightingSchedule must be upstream or global301")
    if schedule == "global301" and effectiveLocalMask is not None and np.any(effectiveLocalMask):
        raise ValueError("global301 requires an empty effective local lighting mask")
    return schedule


def lightingOptimizerForStep(stepIndex: int, schedule: str = "upstream") -> str:
    """Zero-based upstream phases; global301 is an experimental global-only control."""
    validateLightingSchedule(schedule)
    if isinstance(stepIndex, bool) or not isinstance(stepIndex, (int, np.integer)) or stepIndex < 0:
        raise ValueError("stepIndex must be a nonnegative integer")
    if stepIndex > 300:
        return "frozen"
    return "global" if schedule == "global301" or stepIndex <= 100 else "local"


def validateRequest(vertices, faces, uvs, texture, validMask, artifactMask,
                    workingResolution: int, iterations: int, seed: int,
                    skinTone=None, uvFaces=None, lightingSchedule: str = "upstream") -> dict:
    """Validate before CUDA, model movement or allocation; never edit caller arrays."""
    cropForResolution(workingResolution)
    validateLightingSchedule(lightingSchedule)
    if isinstance(iterations, bool) or not isinstance(iterations, (int, np.integer)) or not 1 <= iterations <= 1000:
        raise ValueError("iterations must be an integer between 1 and 1000")
    if isinstance(seed, bool) or not isinstance(seed, (int, np.integer)) or not 0 <= seed < 2 ** 63:
        raise ValueError("seed must be an integer in [0, 2**63)")
    vertices, faces = validateTriangles(vertices, faces, 3)
    uvs, uvFaces = validateTriangles(uvs, faces if uvFaces is None else uvFaces, 2)
    if uvFaces.shape != faces.shape or np.min(uvs) < 0 or np.max(uvs) > 1:
        raise ValueError("Expected matching geometry/UV triangles with OBJ UVs in [0, 1]")
    texture = np.asarray(texture, dtype=np.float32)
    shape = (workingResolution, workingResolution)
    if texture.shape != (*shape, 3) or not np.isfinite(texture).all():
        raise ValueError(f"texture must be finite RGB with shape {(*shape, 3)}")
    if texture.min() < 0 or texture.max() > 1:
        raise ValueError("texture must contain gamma-2.2 encoded RGB values in [0, 1]")
    validMask = validateMask(validMask, shape, "validMask")
    artifactMask = (np.zeros(shape, bool) if artifactMask is None
                    else validateMask(artifactMask, shape, "artifactMask"))
    if not validMask.any():
        raise ValueError("validMask has no observations")
    if skinTone is not None:
        skinTone = np.asarray(skinTone, dtype=np.float32)
        if (skinTone.shape != (3,) or not np.isfinite(skinTone).all()
                or np.any(skinTone <= 0) or np.any(skinTone > 1)):
            raise ValueError("skinTone must be three finite encoded RGB values in (0, 1]")
    return {"vertices": vertices.copy(), "faces": faces.copy(), "uvs": uvs.copy(),
            "uvFaces": uvFaces.copy(), "texture": texture.copy(), "validMask": validMask,
            "artifactMask": artifactMask, "workingResolution": int(workingResolution),
            "iterations": int(iterations), "seed": int(seed), "skinTone": skinTone,
            "lightingSchedule": lightingSchedule}


def readTemplate(path: Path) -> dict:
    """Read the bundled triangular OBJ without merging/reordering indexed vertices."""
    vertices, uvs, faces, uvFaces = [], [], [], []
    for line in path.read_text().splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == "v":
            vertices.append([float(value) for value in fields[1:4]])
        elif fields[0] == "vt":
            uvs.append([float(value) for value in fields[1:3]])
        elif fields[0] == "f":
            if len(fields) != 4:
                raise ValueError("The WildCap ICT template must contain triangular OBJ faces")
            corners = [field.split("/") for field in fields[1:]]
            if any(len(corner) < 2 or not corner[1] for corner in corners):
                raise ValueError("The WildCap ICT template requires face-corner UV indices")
            faces.append([int(corner[0]) - 1 for corner in corners])
            uvFaces.append([int(corner[1]) - 1 for corner in corners])
    vertices, faces = validateTriangles(np.asarray(vertices), np.asarray(faces), 3)
    uvs, uvFaces = validateTriangles(np.asarray(uvs), np.asarray(uvFaces), 2)
    return {"vertices": vertices, "faces": faces, "uvs": uvs, "uvFaces": uvFaces}


def validateAtlas(request: dict, template: dict) -> None:
    """Only positions may change; face order/winding and UV corner layout stay fixed."""
    if (len(request["vertices"]) != len(template["vertices"])
            or not np.array_equal(request["faces"], template["faces"])):
        raise ValueError("Geometry must preserve the bundled ICT vertex/triangle ordering")
    inputCorners = request["uvs"][request["uvFaces"]]
    templateCorners = template["uvs"][template["uvFaces"]]
    if not np.allclose(inputCorners, templateCorners, atol=1e-6, rtol=0):
        raise ValueError("UV corners do not match the fixed ICT training atlas (OBJ V upwards)")


def buildCoordinates(resolution: int, frequencies: int = 4):
    """Match CoordImage exactly, including arange/resolution rather than /(res-1)."""
    import torch

    coordinate = torch.arange(resolution, dtype=torch.float32) / resolution
    ys, xs = torch.meshgrid(coordinate, coordinate, indexing="ij")
    points = 2 * torch.stack([xs, ys], dim=-1) - 1
    channels = [points]
    for index in range(frequencies):
        channels.extend([torch.sin(points * 2 ** index), torch.cos(points * 2 ** index)])
    return torch.cat(channels, dim=-1).permute(2, 0, 1)[None].contiguous()


class WildCapAdapter:
    """One immutable network owner; every optimize() builds its own sampling state.

    ``geometryFrame`` declares the input frame; uniform scale/translation do
    not alter the normals and the free environment can absorb a common rigid
    rotation. ``uvs`` use OBJ (U right, V up); texture arrays use top-left origin. Passing
    uvFaces supports separate geometry and UV indexing at seams. No coordinate
    transform, atlas warp, 4K enlargement, or geometry optimization is performed.
    """

    randomLock = threading.RLock()

    def __init__(self, projectRoot: Path, device: str = "cuda", memoryPolicy: str = "staged"):
        if memoryPolicy not in {"staged", "resident"}:
            raise ValueError("memoryPolicy must be staged or resident")
        self.projectRoot = Path(projectRoot).resolve()
        self.device = str(device)
        self.memoryPolicy = memoryPolicy
        self.loaded = False
        self.model: Any = None
        self.backend: Any = None
        self.modelConfig: dict = {}
        self.template: dict = {}
        self.assets: dict = {}
        self.coordinates: dict = {}
        self.assetHashes: dict = {}
        self.lock = threading.RLock()

    def loadModels(self) -> "WildCapAdapter":
        """Load local weights and immutable atlas assets once, initially onto CPU."""
        with self.lock:
            if self.loaded:
                return self
            sourceRoot = self.projectRoot / "03_WildCap/wildcap"
            weightsRoot = self.projectRoot / "03_WildCap/weights"
            templatePath = self.projectRoot / "assets/wrapPreparation/originals/open_eye_template.obj"
            assetPaths = {
                "faceMask": sourceRoot / "assets/face_mask.png",
                "shadowPrior": sourceRoot / "assets/shadow_prior_mask.png",
                "skinMask": sourceRoot / "assets/skin_color_mask.png",
                "specular": sourceRoot / "assets/init_map/spec_template.png",
                "normal": sourceRoot / "assets/init_map/normal_template.png",
            }
            requiredPaths = [weightsRoot / "config.json", weightsRoot / "ckpt.pth", templatePath,
                             sourceRoot / "k_diffusion/config.py", *assetPaths.values()]
            missingPaths = [str(path) for path in requiredPaths if not path.is_file()]
            if missingPaths:
                raise FileNotFoundError("Missing local WildCap assets: " + ", ".join(missingPaths))

            import torch
            from ..vendor.wildCap.backend import loadBackend

            backend = loadBackend(sourceRoot)
            config = backend.config.load_config(weightsRoot / "config.json")
            if (config["model"]["type"] != "image_v1" or config["model"]["input_channels"] != 7
                    or config["cond"] != {"type": "posenc", "pos_enc_freq": 4}):
                raise ValueError("Expected bundled WildCap image_v1 / 7-channel / posenc-4 checkpoint")
            coordinates = {resolution: buildCoordinates(resolution) for resolution in (512, 1024)}
            config["cond"]["cond_channels"] = coordinates[512].shape[1]
            network = backend.config.make_model(config)
            # Trusted, locally provisioned upstream checkpoint also contains
            # optimizer/RNG training state. Only model_ema enters the network.
            checkpoint = torch.load(weightsRoot / "ckpt.pth", map_location="cpu", weights_only=False)
            network.load_state_dict(checkpoint["model_ema"], strict=True)
            del checkpoint
            model = backend.layers.Denoiser(network, sigma_data=config["model"]["sigma_data"],
                                            data_channel=7).eval().requires_grad_(False)
            assets = {}
            for name, path in assetPaths.items():
                with Image.open(path) as image:
                    assets[name] = np.asarray(image.convert("RGB"), dtype=np.float32) / 255
            self.template = readTemplate(templatePath)
            self.assetHashes = {name: hashlib.sha256(path.read_bytes()).hexdigest()
                                for name, path in {"template": templatePath, **assetPaths}.items()}
            self.model, self.backend = model, backend
            self.modelConfig, self.assets, self.coordinates = config["model"], assets, coordinates
            if self.memoryPolicy == "resident":
                self.moveModels(self.device)
            self.loaded = True
            return self

    def moveModels(self, device: str) -> None:
        self.model.to(device)

    def optimize(self, vertices, faces, uvs, texture, validMask, artifactMask=None, *,
                 workingResolution: int = 512, iterations: int = 599, seed: int = 2026,
                 skinTone=None, uvFaces=None, geometryFrame: str = "ictNative",
                 lightingSchedule: str = "upstream") -> dict:
        if geometryFrame not in {"ictNative", "uvFaceFusionCanonical"}:
            raise ValueError("geometryFrame must be ictNative or uvFaceFusionCanonical")
        request = validateRequest(vertices, faces, uvs, texture, validMask, artifactMask,
                                  workingResolution, iterations, seed, skinTone, uvFaces, lightingSchedule)
        request["geometryFrame"] = geometryFrame
        if not self.loaded:
            raise RuntimeError("Call loadModels() before optimize()")
        validateAtlas(request, self.template)
        self.validateEffectiveLightingSchedule(request)
        if not self.device.startswith("cuda"):
            raise ValueError("WildCap Split-Sum optimization requires a CUDA device")
        import torch

        # Upstream lighting allocates on the active CUDA device and uses global
        # RNG. Restore CPU/all-CUDA RNG states afterwards; serialize this scope
        # across adapter instances, not only requests on one instance.
        with self.lock, self.randomLock, torch.cuda.device(self.device), torch.random.fork_rng():
            torch.manual_seed(request["seed"])
            torch.cuda.manual_seed_all(request["seed"])
            start = perf_counter()
            try:
                self.backend.prepareRenderPlugin()
                self.moveModels(self.device)
                with torch.enable_grad():
                    result = self.runOptimization(request)
                result["diagnostics"]["seconds"] = perf_counter() - start
                return result
            finally:
                if self.memoryPolicy == "staged":
                    self.moveModels("cpu")

    def resizeTensor(self, tensor, resolution: int):
        if tensor.shape[-2:] == (resolution, resolution):
            return tensor
        return self.backend.Resizer(tensor.shape, scale_factor=resolution / tensor.shape[-1]).to(
            tensor.device)(tensor)

    def validateEffectiveLightingSchedule(self, request: dict) -> None:
        """Check global301 against the same resized prior/crop before CUDA entry.

        A zero cropped shadow mask also has a zero morphological edge mask, so
        this emptiness check needs neither the renderer nor geometric normals.
        Nonempty masks outside the trained crop or excluded by the prior remain
        legal. The default path does no new resampling or allocation.
        """
        if request["lightingSchedule"] != "global301" or not request["artifactMask"].any():
            return
        import torch

        prior = torch.from_numpy(np.ascontiguousarray(self.assets["shadowPrior"], dtype=np.float32))
        prior = self.resizeTensor(prior.permute(2, 0, 1)[None], request["workingResolution"])
        shadow = request["artifactMask"] * prior[0, 0].clamp(0, 1).numpy()
        x1, x2, y1, y2 = cropForResolution(request["workingResolution"])
        validateLightingSchedule(request["lightingSchedule"], shadow[y1:y2, x1:x2] > 0)

    def prepareState(self, request: dict) -> dict:
        """Prepare per-request masks, color, fixed geometry normals and initial maps."""
        import kornia
        import torch
        import torch.nn.functional as functional
        import trimesh

        resolution = request["workingResolution"]
        x1, x2, y1, y2 = cropForResolution(resolution)

        def tensor(image):
            image = np.asarray(image, np.float32)
            if image.ndim == 2:
                image = image[..., None]
            return torch.from_numpy(np.ascontiguousarray(image)).permute(2, 0, 1)[None].to(self.device)

        def crop(value):
            return value[..., y1:y2, x1:x2]

        def asset(name):
            return self.resizeTensor(tensor(self.assets[name]), resolution)

        mesh = trimesh.Trimesh(request["vertices"], request["faces"], process=False)
        normals = torch.tensor(np.asarray(mesh.vertex_normals).copy(), dtype=torch.float32,
                               device=self.device)
        normals = functional.normalize(normals, dim=-1)
        # Duplicate per-face corners only for rasterization so UV seams never
        # merge geometry indices or change the surface-normal calculation.
        cornerUvs = torch.tensor(request["uvs"][request["uvFaces"]].reshape(-1, 2),
                                 dtype=torch.float32, device=self.device)
        uvPositions = 2 * cornerUvs - 1
        uvPositions[:, 1] *= -1
        rasterFaces = torch.arange(len(cornerUvs), device=self.device).reshape(-1, 3)
        cornerNormals = normals[torch.tensor(request["faces"].reshape(-1), device=self.device)]
        rasterizer = self.backend.MeshRenderer(self.device)
        normalMap, faceIds = rasterizer.render_ndc({
            "vertice": torch.cat([uvPositions, torch.ones_like(uvPositions[:, :1])], dim=1)[None],
            "faces": rasterFaces[None], "attributes": cornerNormals[None],
            "size": (resolution, resolution),
        })
        geometryMask = (faceIds[..., 0] >= 0)[:, None].float()
        faceMask = asset("faceMask")[:, :1].clamp(0, 1) * geometryMask
        observedMask = tensor(request["validMask"]) * faceMask
        # Confidence is distinct from artifacts: absent texels are excluded
        # from the likelihood instead of fitting zero-filled texture holes.
        artifactMask = tensor(request["artifactMask"]) * asset("shadowPrior")[:, :1].clamp(0, 1)
        skinMask = asset("skinMask")[:, :1].clamp(0, 1) * observedMask * (1 - artifactMask)
        texture = tensor(request["texture"])
        if crop(observedMask).sum().item() <= 0:
            raise ValueError("No observed pixels intersect the trained ICT face crop")
        if crop(skinMask).sum().item() <= 1e-6:
            raise ValueError("No reliable skin pixels remain to constrain color/lighting")
        skinTone = (torch.tensor(request["skinTone"], device=self.device) if request["skinTone"] is not None
                    else (crop(texture) * crop(skinMask)).sum((0, 2, 3)) / crop(skinMask).sum())
        if torch.any(skinTone <= 1e-4):
            raise ValueError("Skin tone is too dark to initialize the albedo/lighting ambiguity")
        initialDiffuse = skinTone[None, :, None, None].expand(1, 3, resolution, resolution).pow(2.2)
        # Upstream creates 1024 templates with torchvision bicubic first.
        from torchvision.transforms import functional as vision
        from torchvision.transforms import InterpolationMode
        initialSpecular = tensor(self.assets["specular"])
        initialNormal = tensor(self.assets["normal"])
        initialSpecular = vision.resize(initialSpecular, [1024, 1024], InterpolationMode.BICUBIC)
        initialNormal = vision.resize(initialNormal, [1024, 1024], InterpolationMode.BICUBIC)
        initialSpecular = self.resizeTensor(initialSpecular, resolution)[:, :1]
        initialNormal = functional.normalize(2 * initialNormal - 1, dim=1)
        initialNormal = self.resizeTensor(initialNormal, resolution)
        guidance = texture.pow(2.2)
        # Normalized convolution prevents black/unobserved texels bleeding into
        # otherwise valid boundary pixels during upstream's 3x3 degradation.
        validSupport = tensor(request["validMask"])
        blurredSupport = kornia.filters.gaussian_blur2d(validSupport, (3, 3), (0.8, 0.8))
        guidance = kornia.filters.gaussian_blur2d(guidance * validSupport, (3, 3), (0.8, 0.8))
        guidance = guidance / blurredSupport.clamp_min(1e-8)
        shadow = crop(artifactMask)
        mainMask = 1 - shadow[0, 0]
        edgeMask = mainMask[None, None] - kornia.morphology.erosion(
            mainMask[None, None], torch.ones(5, 5, device=self.device))
        initialShade = ((crop(guidance) / crop(initialDiffuse).clamp_min(1e-8)) * crop(skinMask)).sum(
            (2, 3)) / crop(skinMask).sum((2, 3))
        return {"initial": crop(torch.cat([2 * initialDiffuse - 1, initialNormal,
                                             2 * initialSpecular - 1], dim=1)),
                "guidance": crop(guidance), "objectNormal": crop(normalMap),
                "faceMask": crop(faceMask), "observedMask": crop(observedMask),
                "skinMask": crop(skinMask), "skinTone": skinTone,
                "edgeMask": edgeMask, "shadowMask": shadow,
                "initialShade": initialShade[0],
                "coordinates": crop(self.coordinates[resolution].to(self.device)),
                "crop": (x1, x2, y1, y2)}

    def runOptimization(self, request: dict) -> dict:
        """Real DPPS and Split-Sum optimization; never calls the upstream CLI/sampler."""
        import kornia
        import torch
        import torch.nn.functional as functional

        state = self.prepareState(request)
        lightingSchedule = request.get("lightingSchedule", "upstream")
        effectiveLocalMask = (state["shadowMask"] + state["edgeMask"]) > 0
        validateLightingSchedule(lightingSchedule, effectiveLocalMask.detach().cpu().numpy())
        degrade = lambda image: kornia.filters.gaussian_blur2d(image, (3, 3), (0.8, 0.8))
        lighting = self.backend.TexelGridLighting(
            device=self.device, seg=effectiveLocalMask.float(),
            init_shade=state["initialShade"], use_init_shade=True, main_light_type="splitsum",
            operator=degrade, envlight_path="", resolution=96)
        mainOptimizer = torch.optim.Adam(lighting.main_light.parameters(), lr=0.01)
        localOptimizer = torch.optim.Adam([lighting.sp_light], lr=0.01)
        mainSchedule = torch.optim.lr_scheduler.ExponentialLR(mainOptimizer, gamma=0.995)
        localSchedule = torch.optim.lr_scheduler.ExponentialLR(localOptimizer, gamma=0.995)
        sampling = self.backend.sampling
        sigmas = sampling.get_sigmas_karras(1000, self.modelConfig["sigma_min"],
                                            self.modelConfig["sigma_max"], rho=7, device=self.device)
        sigmas = sigmas[-(request["iterations"] + 1):]
        generator = torch.Generator(device=self.device).manual_seed(request["seed"])
        random = lambda shape: torch.randn(shape, device=self.device, generator=generator)
        latent = state["initial"] + random(state["initial"].shape) * sigmas[0]
        observedMask = state["observedMask"]
        trace = []
        optimizerCounts = {"globalOptimizerSteps": 0, "localOptimizerSteps": 0,
                           "effectiveLocalOptimizerSteps": 0}
        for stepIndex in range(request["iterations"]):
            latent = latent.detach().requires_grad_(True)
            prediction = self.model(torch.cat([latent, state["coordinates"]], dim=1),
                                    sigmas[stepIndex].expand(1))
            sigmaDown, sigmaUp = sampling.get_ancestral_step(sigmas[stepIndex], sigmas[stepIndex + 1], eta=1)
            direction = sampling.to_d(latent, sigmas[stepIndex], prediction)
            diffuse = (prediction[:, :3] + 1) / 2
            rendered, _, _ = lighting(diffuse, state["objectNormal"], detach=True)
            colorLoss = ((rendered - state["guidance"]) * observedMask).square().sum()
            gradient = torch.autograd.grad(colorLoss, latent)[0] * state["faceMask"]
            maximumGradient = float(gradient.abs().max())
            if not np.isfinite(maximumGradient) or not torch.isfinite(colorLoss):
                raise FloatingPointError(f"WildCap sampling diverged at iteration {stepIndex}")
            # Preserve upstream's decade scaling without an unbounded while.
            if maximumGradient > 0.1:
                gradient = gradient * (0.1 ** np.ceil(np.log10(maximumGradient / 0.1)))
            renderedLight, shade, mainShade = lighting(diffuse.detach(), state["objectNormal"], detach=False)
            lightLoss = ((renderedLight - state["guidance"]) * observedMask).square().sum()
            regularization = functional.relu(shade - mainShade).square().sum()
            vertical = ((shade[..., 1:, :] - shade[..., :-1, :]) * state["edgeMask"][..., 1:, :]).abs().sum()
            horizontal = ((shade[..., :, 1:] - shade[..., :, :-1]) * state["edgeMask"][..., :, 1:]).abs().sum()
            totalLightLoss = lightLoss + regularization + 0.1 * (vertical + horizontal)
            if not torch.isfinite(totalLightLoss):
                raise FloatingPointError(f"WildCap lighting diverged at iteration {stepIndex}")
            mainOptimizer.zero_grad(set_to_none=True)
            localOptimizer.zero_grad(set_to_none=True)
            optimizerName = lightingOptimizerForStep(stepIndex, lightingSchedule)
            localGradientMaxAbs = None
            if optimizerName != "frozen":
                totalLightLoss.backward()
                localGradient = lighting.sp_light.grad
                localGradientMaxAbs = (float(localGradient.detach().abs().max())
                                       if localGradient is not None else None)
                optimizer, scheduler = ((mainOptimizer, mainSchedule) if optimizerName == "global"
                                        else (localOptimizer, localSchedule))
                optimizer.step()
                scheduler.step()
                optimizerCounts["globalOptimizerSteps" if optimizerName == "global"
                                else "localOptimizerSteps"] += 1
                if optimizerName == "local" and localGradientMaxAbs is not None and localGradientMaxAbs > 0:
                    optimizerCounts["effectiveLocalOptimizerSteps"] += 1
            with torch.no_grad():
                delta = sigmaDown - sigmas[stepIndex]
                nextLatent = latent + direction * delta - gradient
                if sigmas[stepIndex + 1] > 0:
                    currentRendered, currentLighting, _ = lighting((latent[:, :3] + 1) / 2,
                                                                  state["objectNormal"])
                    target = (1 + delta / sigmas[stepIndex]) * currentRendered - (
                        delta / sigmas[stepIndex]) * state["guidance"]
                    # Stream the 20 DPPS candidates to avoid a 20x full-atlas
                    # allocation while retaining the same selection objective.
                    bestLoss, bestCandidate = float("inf"), None
                    for _ in range(20):
                        candidate = nextLatent + random(nextLatent.shape) * sigmaUp
                        candidateRendered = currentLighting * ((candidate[:, :3] + 1) / 2)
                        candidateLoss = float(((candidateRendered - target) * observedMask).square().sum())
                        if candidateLoss < bestLoss:
                            bestLoss, bestCandidate = candidateLoss, candidate
                    if bestCandidate is None:
                        raise FloatingPointError(f"No finite DPPS candidate at iteration {stepIndex}")
                    nextLatent = bestCandidate
                latent = nextLatent.detach()
            if stepIndex == 0 or stepIndex % 25 == 0 or stepIndex == request["iterations"] - 1:
                trace.append({"iteration": stepIndex + 1, "photometricSum": float(colorLoss.detach()),
                              "lightingSum": float(totalLightLoss.detach()),
                              "optimizer": optimizerName, "localGradientMaxAbs": localGradientMaxAbs,
                              **optimizerCounts})
                logger.info("WildCap iteration %d/%d: photometric loss %.6g, lighting loss %.6g",
                            stepIndex + 1, request["iterations"], trace[-1]["photometricSum"],
                            trace[-1]["lightingSum"])
            # Release the denoiser activation graph before the next forward.
            finalPrediction = prediction.detach()
            del prediction, direction, diffuse, rendered, colorLoss, gradient
            del renderedLight, shade, mainShade, lightLoss, regularization, totalLightLoss
        state["lightingDiagnostics"] = {"lightingSchedule": lightingSchedule, **optimizerCounts}
        state["lightingForAudit"] = lighting
        return self.finishResult(finalPrediction, state, request, trace)

    def finishResult(self, prediction, state: dict, request: dict, trace: list) -> dict:
        import torch
        import torch.nn.functional as functional

        with torch.no_grad():
            diffuse = ((prediction[:, :3] + 1) / 2).clamp_min(0).pow(1 / 2.2)
            skinMean = (diffuse * state["skinMask"]).sum((0, 2, 3)) / state["skinMask"].sum()
            diffuse = diffuse * (state["skinTone"] / skinMean.clamp_min(1e-6))[None, :, None, None]
            specular = (prediction[:, 6:7] + 1) / 2
            normal = functional.normalize(prediction[:, 3:6], dim=1)
            if not all(torch.isfinite(item).all() for item in (diffuse, specular, normal)):
                raise FloatingPointError("WildCap generated nonfinite material maps")
            support = state["faceMask"] > 0.5
            if torch.any((torch.linalg.vector_norm(normal, dim=1, keepdim=True) < 0.5) & support):
                raise FloatingPointError("WildCap produced a degenerate tangent normal inside the face")
            observed = (state["observedMask"] > 0.5) & support
            clippedFraction = float(((diffuse < 0) | (diffuse > 1)).float().mean())
            resolution = request["workingResolution"]
            x1, x2, y1, y2 = state["crop"]

            def canvas(value):
                output = np.zeros((resolution, resolution, value.shape[1]), np.float32)
                output[y1:y2, x1:x2] = value[0].permute(1, 2, 0).float().cpu().numpy()
                return output

            outputMask = canvas(observed)[:, :, 0].astype(bool)
            generatedMask = canvas(support)[:, :, 0].astype(bool)
            if not outputMask.any():
                raise ValueError("WildCap returned no valid observed pixels inside its trained face crop")
            localLightingMask = (state["shadowMask"] + state["edgeMask"]) > 0
            localLightingTexelCount = int(localLightingMask.sum().item())
            lightingMode = "globalAndLocal" if localLightingTexelCount else "globalOnly"
            warnings = ["specularAndTangentNormalsArePriorDriven",
                        "delightedInputIsNotCalibratedReflectance",
                        "unobservedTexelsMustNotBeReportedAsMeasured"]
            if not localLightingTexelCount:
                warnings.append("localTexelGridLightingInactiveWithoutEffectiveArtifactMask")
            result = {"diffuse": canvas(diffuse.clamp(0, 1) * support),
                    "specular": canvas(specular.clamp(0, 1) * support)[:, :, 0],
                    "tangentNormal": canvas(normal * support), "validMask": outputMask,
                    "generatedMask": generatedMask, "inferredMask": generatedMask & ~outputMask,
                    "effectiveLocalMask": canvas(localLightingMask)[:, :, 0].astype(bool),
                    "skinMask": canvas(state["skinMask"])[:, :, 0],
                    "diagnostics": {"status": "experimental", "algorithm": "wildCapDppsSplitSum",
                        "lightingMode": lightingMode, "localLightingTexelCount": localLightingTexelCount,
                        "iterations": request["iterations"], "scheduleLength": 1000,
                        "initialization": "uniformSkinTonePlusSpecularAndNormalTemplates",
                        "workingResolution": resolution, "outputResolution": resolution,
                        "seed": request["seed"], "cropXxyy": list(state["crop"]),
                        "diffuseEncoding": "gamma2.2", "specularEncoding": "linearScalar",
                        "normalEncoding": "signedUnitTangentVector",
                        "uvConvention": "OBJ: u right, v up; arrays: row down",
                        "geometryFrame": request["geometryFrame"], "geometryTransformsApplied": [],
                        "skinTone": state["skinTone"].cpu().tolist(),
                        "skinToneSource": "explicit" if request["skinTone"] is not None else "observedReliableSkinMean",
                        "diffuseClippedFraction": clippedFraction,
                        "observedPixelCount": int(outputMask.sum()),
                        "inferredPixelCount": int((generatedMask & ~outputMask).sum()),
                        "artifactMaskProvided": bool(request["artifactMask"].any()),
                        "assetHashes": dict(self.assetHashes), "lossTrace": trace,
                        "warnings": warnings}}
            result["diagnostics"].update(state.get("lightingDiagnostics", {
                "lightingSchedule": request.get("lightingSchedule", "upstream"),
                "globalOptimizerSteps": 0, "localOptimizerSteps": 0,
                "effectiveLocalOptimizerSteps": 0}))
            if "lightingForAudit" in state:
                # Material arrays above are complete before this extra forward.
                # Audit likelihood uses the unnormalized linear denoiser diffuse,
                # exactly as the optimization, not the skin-tone-normalized export.
                rendered, shading, mainShading = state["lightingForAudit"](
                    (prediction[:, :3] + 1) / 2, state["objectNormal"], detach=True)
                audit = {"fittedShading": shading, "fittedMainShading": mainShading,
                         "renderedGuidance": rendered, "guidance": state["guidance"]}
                if not all(torch.isfinite(value).all() for value in audit.values()):
                    raise FloatingPointError("WildCap generated nonfinite lighting audit maps")
                result.update({name: canvas(value) for name, value in audit.items()})
                result["diagnostics"]["lightingAuditEncoding"] = "linearBeforeExportSkinToneRenormalization"
            return result
